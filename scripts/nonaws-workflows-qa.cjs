const fs=require('fs'),assert=require('assert'),{chromium}=require('playwright');
let activePage;
const words=JSON.parse(fs.readFileSync('packages/ui/assets/ui_en.arb','utf8'));
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 activePage=page;
 page.on('response',async r=>{if(r.url().endsWith('/v1/assistant')) console.log('assistant response',r.status(),await r.text());});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://localhost:8080');
 await page.getByRole('textbox',{name:'Demo access code'}).fill(fs.readFileSync('.local/demo-access-code','utf8').trim());
 await page.getByRole('button',{name:'Open demo',exact:true}).click();
 await page.getByRole('button',{name:'Demo capabilities Tab 6 of 6',exact:true}).click();
 await page.getByRole('button',{name:'Manage help content',exact:true}).click();
 await page.getByRole('textbox',{name:'Title',exact:true}).waitFor();
 await page.getByRole('textbox',{name:'Title',exact:true}).click();
 await page.waitForTimeout(200);
 assert((await page.getByRole('textbox',{name:'Title',exact:true}).inputValue()).length>0);
 await page.screenshot({path:'output/nonaws/web-content-editor.png'});
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await page.getByRole('button',{name:words.reports,exact:true}).click();
 await page.getByRole('button',{name:words.downloadCsv,exact:true}).waitFor();
 const download=page.waitForEvent('download');
 await page.getByRole('button',{name:words.downloadCsv,exact:true}).click();
 const file=await download;await file.saveAs('.local/nonaws-report.csv');
 const csv=fs.readFileSync('.local/nonaws-report.csv','utf8');assert(csv.includes('confirmed_savings_paise'));assert(csv.includes('Rani'));
 await page.screenshot({path:'output/nonaws/web-reports.png'});

 await page.getByRole('button',{name:'Demo capabilities Tab 6 of 6',exact:true}).click();
 await page.getByRole('button',{name:words.administration,exact:true}).click();
 await page.getByRole('button',{name:words.addIdentity,exact:true}).waitFor();
 await page.screenshot({path:'output/nonaws/web-administration.png'});
 await page.getByRole('textbox',{name:words.importPayload,exact:true}).fill('{}');
 await page.getByRole('button',{name:words.validateImport,exact:true}).click();
 await page.getByText(/INVALID_PAYLOAD/).waitFor();
 await page.getByRole('button',{name:words.addIdentity,exact:true}).click();
 await page.getByRole('textbox',{name:words.identitySubject,exact:true}).waitFor();
 await page.screenshot({path:'output/nonaws/web-access-editor.png'});
 await page.getByRole('button',{name:words.cancel,exact:true}).click();
 await page.getByRole('button',{name:'Demo capabilities Tab 6 of 6',exact:true}).click();
 await page.getByRole('button',{name:words.assistantTitle,exact:true}).click();
 const command=page.getByRole('textbox',{name:words.command,exact:true});
 await command.click(); await page.waitForTimeout(200);
 await command.fill(''); await command.pressSequentially('save 500');
 assert.equal(await command.inputValue(),'save 500');
 await page.waitForTimeout(200);
 assert(await page.getByRole('button',{name:words.openCommand,exact:true}).isDisabled());
 await page.getByRole('textbox',{name:words.helpQuestion,exact:true}).fill('save savings');
 await page.waitForTimeout(300);
 await page.getByRole('button',{name:words.askHelp,exact:true}).click();
 await page.waitForTimeout(500);
 await page.mouse.move(900,700); await page.mouse.wheel(0,500);
 await page.waitForFunction(()=>document.querySelector('flt-semantics-host')?.textContent?.includes('Save a contribution') || [...document.querySelectorAll('[aria-label]')].some(e=>e.getAttribute('aria-label')?.includes('Source: save-contribution')));
 assert((await page.locator('body').ariaSnapshot()).includes('Source: save-contribution'));
 assert((await page.locator('body').ariaSnapshot()).includes(words.unsupportedCommand));
 await page.screenshot({path:'output/nonaws/web-assistance.png'});
 await page.mouse.wheel(0,-1500); await page.waitForTimeout(400);
 await page.getByRole('button',{name:words.startListening,exact:true}).click();
 await page.getByText(words.microphoneDisclosure,{exact:true}).waitFor();
 await page.getByRole('button',{name:words.cancel,exact:true}).click();
 assert.deepEqual(errors,[]);fs.writeFileSync('docs/evidence/nonaws-workflows.json',JSON.stringify({checkedAt:new Date().toISOString(),contentEditorOpened:true,reportDownloaded:true,administrationOpened:true,invalidImportRejected:true,accessEditorOpened:true,citedHelpMatched:true,moneyCommandRejected:true,microphoneConsentShown:true,consoleErrors:errors},null,2));
 await browser.close();
})().catch(async e=>{if(activePage){fs.writeFileSync('.local/nonaws-workflow-failure.txt',await activePage.locator('body').ariaSnapshot());await activePage.screenshot({path:'output/nonaws/workflow-failure.png'});}console.error(e);process.exit(1)});
